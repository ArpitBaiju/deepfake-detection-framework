    "def evaluate_model(model, loader, criterion, device):\n",
    "    model.eval()\n",
    "    total_loss = 0.0\n",
    "    y_true, y_prob = [], []\n",
    "    \n",
    "    with torch.no_grad():\n",
    "        for imgs, labels in loader:\n",
    "            imgs = imgs.to(device, non_blocking=True)\n",
    "            labels = labels.to(device, non_blocking=True).unsqueeze(1)\n",
    "            with autocast(enabled=torch.cuda.is_available()):\n",
    "                logits = model(imgs)\n",
    "                loss = criterion(logits, labels)\n",
    "                probs = torch.sigmoid(logits)\n",
    "            total_loss += loss.item()\n",
    "            y_true.extend(labels.cpu().squeeze().tolist())\n",
    "            y_prob.extend(probs.cpu().squeeze().tolist())\n",
    "            \n",
    "    y_true = np.array(y_true)\n",
    "    y_prob = np.array(y_prob)\n",
    "    y_pred = (y_prob >= 0.5).astype(int)\n",
    "    \n",
    "    return {\n",
    "        'loss': total_loss / len(loader),\n",
    "        'accuracy': float(accuracy_score(y_true, y_pred)),\n",
    "        'precision': float(precision_score(y_true, y_pred, zero_division=0)),\n",
    "        'recall': float(recall_score(y_true, y_pred, zero_division=0)),\n",
    "        'f1': float(f1_score(y_true, y_pred, zero_division=0)),\n",
    "        'roc_auc': float(roc_auc_score(y_true, y_prob)),\n",
    "        'cm': confusion_matrix(y_true, y_pred).tolist()\n",
    "    }\n",
    "\n",
    "def train_full_pipeline(model, train_loader, val_loader, epochs=12, lr=1e-4, wd=1e-4, patience=4, model_name='dafnet_v1'):\n",
    "    model = model.to(device)\n",
    "    criterion = nn.BCEWithLogitsLoss()\n",
    "    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=wd)\n",
    "    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs, eta_min=1e-6)\n",
    "    scaler = GradScaler(enabled=torch.cuda.is_available())\n",
    "    \n",
    "    best_f1 = -1.0\n",
    "    best_epoch = -1\n",
    "    patience_counter = 0\n",
    "    total_batches = len(train_loader)\n",
    "    \n",
    "    history = {\n",
    "        'train_loss': [], 'val_loss': [],\n",
    "        'val_accuracy': [], 'val_precision': [], 'val_recall': [],\n",
    "        'val_f1': [], 'val_roc_auc': []\n",
    "    }\n",
    "    \n",
    "    print(f'\\n======================================================')\n",
    "    print(f'Starting Full Training for {model_name} on {device}')\n",
    "    print(f'Total Planned Epochs: {epochs} | Batches/Epoch: {total_batches:,} | Early Stopping Patience: {patience}')\n",
    "    print(f'======================================================')\n",
    "    \n",
    "    for epoch in range(1, epochs + 1):\n",
    "        model.train()\n",
    "        epoch_loss = 0.0\n",
    "        epoch_start = time.time()\n",
    "        \n",
    "        for step, (imgs, labels) in enumerate(train_loader, 1):\n",
    "            imgs = imgs.to(device, non_blocking=True)\n",
    "            labels = labels.to(device, non_blocking=True).unsqueeze(1)\n",
    "            \n",
    "            optimizer.zero_grad(set_to_none=True)\n",
    "            with autocast(enabled=torch.cuda.is_available()):\n",
    "                logits = model(imgs)\n",
    "                loss = criterion(logits, labels)\n",
    "                \n",
    "            scaler.scale(loss).backward()\n",
    "            scaler.step(optimizer)\n",
    "            scaler.update()\n",
    "            \n",
    "            epoch_loss += loss.item()\n",
    "            \n",
    "            # Live feedback every 250 batches\n",
    "            if step % 250 == 0 or step == total_batches:\n",
    "                elapsed = time.time() - epoch_start\n",
    "                avg_loss = epoch_loss / step\n",
    "                speed = step / elapsed\n",
    "                print(f'  [Epoch {epoch:02d}/{epochs:02d}] Step {step:04d}/{total_batches:04d} | Running Loss: {avg_loss:.4f} | {speed:.1f} batches/sec')\n",
    "                \n",
    "        # Epoch evaluation\n",
    "        print(f'Evaluating epoch {epoch:02d} on validation set ...')\n",
    "        val_metrics = evaluate_model(model, val_loader, criterion, device)\n",
    "        scheduler.step()\n",
    "        \n",
    "        train_loss = epoch_loss / total_batches\n",
    "        val_loss = val_metrics['loss']\n",
    "        val_f1 = val_metrics['f1']\n",
    "        val_auc = val_metrics['roc_auc']\n",
    "        val_acc = val_metrics['accuracy']\n",
    "        epoch_duration = time.time() - epoch_start\n",
    "        \n",
    "        history['train_loss'].append(train_loss)\n",
    "        history['val_loss'].append(val_loss)\n",
    "        history['val_accuracy'].append(val_acc)\n",
    "        history['val_precision'].append(val_metrics['precision'])\n",
    "        history['val_recall'].append(val_metrics['recall'])\n",
    "        history['val_f1'].append(val_f1)\n",
    "        history['val_roc_auc'].append(val_auc)\n",
    "        \n",
    "        print(f'\\n>>> Epoch [{epoch:02d}/{epochs:02d}] Completed in {epoch_duration/60:.1f}m:')\n",
    "        print(f'    Train Loss: {train_loss:.4f} | Val Loss: {val_loss:.4f}')\n",
    "        print(f'    Val Acc:    {val_acc:.4f} | Val F1: {val_f1:.4f} | ROC-AUC: {val_auc:.4f} | Precision: {val_metrics[\"precision\"]:.4f} | Recall: {val_metrics[\"recall\"]:.4f}')\n",
    "        print(f'    Confusion Matrix: {val_metrics[\"cm\"]}\\n')\n",
    "        \n",
    "        # Checkpoint based on F1\n",
    "        if val_f1 > best_f1:\n",
    "            best_f1 = val_f1\n",
    "            best_epoch = epoch\n",
    "            patience_counter = 0\n",
    "            torch.save({\n",
    "                'epoch': epoch,\n",
    "                'model_state_dict': model.state_dict(),\n",
    "                'metrics': val_metrics,\n",
    "                'history': history\n",
    "            }, f'{model_name}_best.pth')\n",
    "            print(f'  --> [CHECKPOINT SAVED]: Best validation F1 achieved ({best_f1:.4f}) at epoch {epoch}.\\n')\n",
